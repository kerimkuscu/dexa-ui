// Generates src/icons.ts, src/all.ts and svg/*.svg from drawings.mjs.
//
//   pnpm draw          write the files
//   pnpm draw --check  fail if they are out of date (used by the tests)
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { drawings } from './drawings.mjs'
import { bounds, centered, clear, toPathData } from './geometry.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const HEADER = '// Generated by `pnpm draw` from scripts/drawings.mjs. Do not edit.\n'

/** `chevron-down` → `iconChevronDown` */
export const exportName = (name) =>
  'icon' + name.replace(/(^|-)([a-z0-9])/g, (_, _dash, c) => c.toUpperCase())

/** Draws every icon. Returns name, path data, flags and bounding box. */
export function drawAll() {
  let group = ''
  return drawings.map((icon) => {
    clear()
    const item = icon.draw()
    if (icon.center !== false) centered(item, icon.center ?? 'xy')
    group = icon.group ?? group
    const b = bounds(item)
    return {
      name: icon.name,
      group,
      rtl: Boolean(icon.rtl),
      path: toPathData(item),
      box: [b.x, b.y, b.width, b.height].map((n) => Math.round(n * 100) / 100),
    }
  })
}

export function generate() {
  const icons = drawAll()
  const ts =
    HEADER +
    "import type { IconData } from './types'\n" +
    icons
      .map(
        (i) =>
          `\n/** ${i.name} */\nexport const ${exportName(i.name)}: IconData = {\n  name: '${i.name}',\n  path: '${i.path}',${i.rtl ? '\n  rtl: true,' : ''}\n}\n`,
      )
      .join('')
  const groups = [...new Set(icons.map((i) => i.group))]
  const all =
    HEADER +
    `import {\n${icons.map((i) => `  ${exportName(i.name)},\n`).join('')}} from './icons'\n` +
    "import type { IconData } from './types'\n\n" +
    '/** Every icon, by gallery group. Imports the whole set: use it for galleries, not in apps. */\n' +
    'export const iconGroups: readonly { name: string; icons: readonly IconData[] }[] = [\n' +
    groups
      .map(
        (g) =>
          `  {\n    name: '${g}',\n    icons: [${icons
            .filter((i) => i.group === g)
            .map((i) => exportName(i.name))
            .join(', ')}],\n  },\n`,
      )
      .join('') +
    ']\n\n/** Every icon, in gallery order. */\nexport const allIcons: readonly IconData[] = iconGroups.flatMap((g) => g.icons)\n'
  const svgs = Object.fromEntries(
    icons.map((i) => [
      `${i.name}.svg`,
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="currentColor"><path d="${i.path}"/></svg>\n`,
    ]),
  )
  return { icons, files: { 'src/icons.ts': ts, 'src/all.ts': all }, svgs }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { icons, files, svgs } = generate()
  if (process.argv.includes('--check')) {
    const stale = Object.entries(files).filter(
      ([file, content]) => readFileSync(resolve(root, file), 'utf8') !== content,
    )
    if (stale.length) {
      console.error(`Out of date: ${stale.map(([f]) => f).join(', ')}. Run \`pnpm draw\`.`)
      process.exit(1)
    }
  } else {
    for (const [file, content] of Object.entries(files)) writeFileSync(resolve(root, file), content)
    const svgDir = resolve(root, 'svg')
    rmSync(svgDir, { recursive: true, force: true })
    mkdirSync(svgDir)
    for (const [file, content] of Object.entries(svgs))
      writeFileSync(resolve(svgDir, file), content)
    console.log(
      `${icons.length} icons → src/icons.ts, src/all.ts, svg/ (${readdirSync(svgDir).length} files)`,
    )
    for (const i of icons) {
      const [x, y, w, h] = i.box
      const out = x < 0.5 || y < 0.5 || x + w > 23.5 || y + h > 23.5 ? '  ← near the edge' : ''
      console.log(
        `${i.name.padEnd(18)} ${w.toFixed(2).padStart(5)} × ${h.toFixed(2).padStart(5)}  ${String(i.path.length).padStart(4)} chars${out}`,
      )
    }
  }
  // paper.js leaves a handle open.
  process.exit(0)
}
