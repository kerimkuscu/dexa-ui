import { scale } from './scale'
import { deriveWeights, shadeFor } from './themes/derive'
import { intents, type Theme } from './themes/types'

export const PREFIX = 'dx'

/** `cssVar('space', '4')` → `--dx-space-4`. Keys named `default` are dropped. */
export function cssVar(...parts: string[]): string {
  return `--${[PREFIX, ...parts.filter((p) => p !== 'default')].join('-')}`
}

function block(selector: string, declarations: [string, string][]): string {
  const body = declarations.map(([name, value]) => `  ${name}: ${value};`).join('\n')
  return `${selector} {\n${body}\n}\n`
}

const pct = (n: number) => `${Math.round(n * 100)}%`

/** Theme-independent tokens on `:root`. */
export function scaleCss(): string {
  const declarations: [string, string][] = []
  for (const [group, values] of Object.entries(scale)) {
    for (const [key, value] of Object.entries(values)) {
      declarations.push([cssVar(group, key), value])
    }
  }
  return block(':root', declarations)
}

/**
 * The theme's own colors. Every theme declares every variable (including the
 * intent `text` colors) so nested `data-theme` regions never inherit a value
 * from an outer theme.
 */
export function themeDeclarations(theme: Theme): [string, string][] {
  const c = theme.colors
  const d: [string, string][] = [['color-scheme', theme.scheme]]
  for (const intent of intents) {
    const { solid, contrast, text } = c.intents[intent]
    d.push([cssVar('color', intent), solid])
    d.push([cssVar('color', intent, 'contrast'), contrast])
    d.push([cssVar('color', intent, 'shade'), shadeFor(contrast)])
    d.push([
      cssVar('color', intent, 'text'),
      text ??
        `color-mix(in oklab, ${solid} ${pct(deriveWeights.text)}, var(${cssVar('text')}))`,
    ])
  }
  d.push(
    [cssVar('bg'), c.bg],
    [cssVar('bg', 'surface'), c.surface],
    [cssVar('bg', 'elevated'), c.elevated],
    [cssVar('bg', 'muted'), c.muted],
    [cssVar('text'), c.text],
    [cssVar('text', 'muted'), c.textMuted],
    [cssVar('text', 'subtle'), c.textSubtle],
    [cssVar('border'), c.border],
    [cssVar('border', 'strong'), c.borderStrong],
    [cssVar('shadow', 'color'), c.shadow],
  )
  return d
}

export function themeCss(theme: Theme, selector = `[data-theme="${theme.name}"]`): string {
  return block(selector, themeDeclarations(theme))
}

/**
 * Colors computed from the theme colors with `color-mix()`. Declared on every
 * themed element (not only `:root`) so nested `data-theme` regions recompute them.
 */
export function derivedCss(): string {
  const w = deriveWeights
  const d: [string, string][] = []
  for (const i of intents) {
    const solid = `var(${cssVar('color', i)})`
    const shade = `var(${cssVar('color', i, 'shade')})`
    d.push(
      [cssVar('color', i, 'hover'), `color-mix(in oklab, ${solid}, ${shade} ${pct(w.hover)})`],
      [cssVar('color', i, 'active'), `color-mix(in oklab, ${solid}, ${shade} ${pct(w.active)})`],
      [
        cssVar('color', i, 'subtle'),
        `color-mix(in oklab, ${solid} ${pct(w.subtle)}, var(${cssVar('bg', 'surface')}))`,
      ],
      [
        cssVar('color', i, 'subtle', 'hover'),
        `color-mix(in oklab, ${solid} ${pct(w.subtleHover)}, var(${cssVar('bg', 'surface')}))`,
      ],
      [
        cssVar('color', i, 'subtle', 'border'),
        `color-mix(in oklab, ${solid} ${pct(w.subtleBorder)}, var(${cssVar('bg', 'surface')}))`,
      ],
    )
  }
  d.push([
    cssVar('focus-ring'),
    `0 0 0 var(${cssVar('focus-ring-width')}) color-mix(in oklab, var(${cssVar('color', 'primary')}) 40%, transparent)`,
  ])
  return block(':root,\n[data-theme]', d)
}

export interface BuildCssOptions {
  /** Theme applied when no `data-theme` attribute is present. */
  defaultTheme: Theme
  /** Theme used for `data-theme="auto"` when the OS prefers dark. */
  autoDarkTheme: Theme
  themes: readonly Theme[]
}

/** Full token stylesheet: scale + every theme + derived colors. */
export function buildCss({ defaultTheme, autoDarkTheme, themes }: BuildCssOptions): string {
  const parts = [
    '/* dexa-ui design tokens — generated by @dexa-ui/tokens, do not edit. */\n',
    scaleCss(),
    themeCss(defaultTheme, `:root,\n[data-theme="${defaultTheme.name}"],\n[data-theme="auto"]`),
  ]
  for (const theme of themes) {
    if (theme.name !== defaultTheme.name) parts.push(themeCss(theme))
  }
  const auto = themeDeclarations(autoDarkTheme)
    .map(([n, v]) => `    ${n}: ${v};`)
    .join('\n')
  parts.push(`@media (prefers-color-scheme: dark) {\n  [data-theme="auto"] {\n${auto}\n  }\n}\n`)
  parts.push(derivedCss())
  return parts.join('\n')
}
